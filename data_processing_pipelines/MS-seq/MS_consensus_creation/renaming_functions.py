import pandas as pd

def mature_ribosome_chromname_renaming(code:str)->str:
    """
    Map various mature ribosomal RNA chrom name codes to a canonical short form.

    Parameters:
    code (str): Chromosome name or code to translate.

    Returns:
    str: Canonical chrom name if found, otherwise returns the original code.
    """
    chromname_dict = {
    "hs_rRNA_18S":"18S",
    "hs_rRNA_28S":"28S",
    "hs_rRNA_5.8S":"5.8S",
    "hs_rRNA_5S":"5S",
    "18S":"18S",
    "28S":"28S",
    "5.8S":"5.8S",
    "5S":"5S"}
    try:
        return chromname_dict[code]
    except KeyError:
        return code

